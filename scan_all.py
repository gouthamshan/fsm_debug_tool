#!/usr/bin/env python3
"""
Drop-folder AO scanner - no browser needed.
Put AO bundles (.tar, .tgz, .tar.gz, .zip) in input/ (or input/<investigation>/),
then run:  python3 scan_all.py            (scan everything in input/)
           python3 scan_all.py --watch    (keep watching input/ every 30s)
           python3 scan_all.py <name>     (only input/<name>/)

For each bundle it:
  - untars safely (colon-safe filenames for Windows-origin tars)
  - classifies backend / appsvr (pm2+GlassFish) / system / postgres / upgrade
  - validates Redis: 6666.conf + redis_info.out + log counts (maxclients proof, replication, restarts)
  - parses minidumps: signal, crash thread, IST time, tcmalloc invalid free
  - detects: Jedis pool not open, lookup table cannot load, FortiGuard feed load,
    shared buffer drops, GlassFish restarts via server.log rotation,
    phRuleWorker blocking, segfaults in dmesg, disk/memory pressure
  - tags every restart/start/stop with [RESTART-ALERT], labels CRITICAL first
Reports go to reports/<bundle>_AO_ANALYSIS_REPORT.md and a combined reports/SUMMARY.md
Stdlib only. Local only, 127.0.0.1 not involved - no browser, no server.
"""
import collections, hashlib, json, os, re, sys, time
from pathlib import Path

BASE = Path(__file__).resolve().parent
INPUT = BASE / "input"
REPORTS = BASE / "reports"
ANALYSIS = BASE / "analysis"
INPUT.mkdir(exist_ok=True); REPORTS.mkdir(exist_ok=True); ANALYSIS.mkdir(exist_ok=True)
(Path(INPUT)/"README.txt").write_text(
    "Put AO log bundles here.\n"
    "Examples: worker1_AOlogs.tar, SuperAOlogs.tar, or a subfolder per investigation:\n"
    "  input/worker1/worker1_AOlogs.tar\n"
    "  input/super/SuperAOlogs.tar\n"
    "Supported: .tar .tgz .tar.gz .zip\n"
    "Then run:  ./scan.sh            (or python3 scan_all.py)\n"
    "Watch mode: ./scan.sh --watch  (auto-scans new files every 30s, no browser)\n"
    "Reports appear in ../reports/ and a combined SUMMARY.md\n", encoding="utf-8")

sys.path.insert(0, str(BASE))
import analyze_ao as AO

def find_bundles(target: Path):
    out=[]
    for ext in ("*.tar","*.tgz","*.tar.gz","*.zip"):
        out.extend(target.rglob(ext))
    # de-dupe, skip reports
    seen=set(); uniq=[]
    for p in sorted(out):
        if p not in seen and "reports" not in p.parts:
            seen.add(p); uniq.append(p)
    return uniq

def process_one(bundle: Path, out_root: Path):
    label = bundle.name
    safe = re.sub(r'[^A-Za-z0-9._\-]', '_', bundle.stem)
    work = out_root / safe
    work.mkdir(parents=True, exist_ok=True)
    print(f"\n=== {bundle} ===", flush=True)
    # extract (colon-safe, like Super tar with ansible-2024-..._12:42:22.log)
    import tarfile, zipfile
    extracted = work / "extracted"
    if not extracted.exists():
        extracted.mkdir(parents=True, exist_ok=True)
        if zipfile.is_zipfile(bundle):
            with zipfile.ZipFile(bundle) as z: z.extractall(extracted)
        else:
            with tarfile.open(bundle) as t:
                for m in t.getmembers():
                    if '..' in m.name or m.name.startswith('/'): continue
                    safe_name = re.sub(r'[:*?"<>|]', '_', m.name)
                    target = extracted / safe_name
                    if m.isdir(): target.mkdir(parents=True, exist_ok=True); continue
                    target.parent.mkdir(parents=True, exist_ok=True)
                    f = t.extractfile(m)
                    if f is not None: target.write_bytes(f.read())
    root = extracted / "AOLogs" if (extracted/"AOLogs").exists() else extracted
    # If tar contained nested AOLogs/... already handled above; if root still has subfolders, analyze root
    res = AO.analyze(root)
    md = AO.render_md(label, res)
    report_md = REPORTS / f"{safe}_AO_ANALYSIS_REPORT.md"
    report_md.write_text(md, encoding="utf-8")
    (work/"AO_ANALYSIS_REPORT.json").write_text(json.dumps(res, indent=2, default=str), encoding="utf-8")
    crit = [i for i in res["issues"] if i["sev"]=="CRITICAL"]
    print(f"  files={res['total_files']} issues={len(res['issues'])} CRITICAL={len(crit)} restarts={len(res['restarts'])}")
    print(f"  report: {report_md}")
    for i in crit[:8]:
        print(f"    [CRITICAL] {i['proc']} {i['type']} - {i['file']}")
    for r in res["restarts"][:3]:
        print(f"    [RESTART-ALERT] {r['file']}: {r['line'][:140]}")
    return {"bundle":str(bundle),"report":str(report_md),"files":res["total_files"],"issues":len(res["issues"]),"critical":len(crit),"restarts":len(res["restarts"]),
            "by_proc":{k:len(v) for k,v in res["by_proc"].items()},
            "redis":res.get("redis_validation",{}).get("log_counts",{}),
            "critical_items":crit[:20]}

def write_summary(results, extra=""):
    lines=["# AO Investigation Summary","","Generated by scan_all.py - drop-folder mode, no browser","",""]
    for r in results:
        lines.append(f"## {r['bundle']}")
        lines.append(f"- Report: {r['report']}")
        lines.append(f"- Files: {r['files']}, Issues: {r['issues']}, CRITICAL: {r['critical']}, Restarts: {r['restarts']}")
        lines.append(f"- By process: {r['by_proc']}")
        if r.get("redis"): lines.append(f"- Redis log counts: {r['redis']}")
        lines.append("- CRITICAL items:")
        for i in r["critical_items"]:
            lines.append(f"  - [CRITICAL] [{i['proc']}] {i['type']} - {i['file']}")
            lines.append(f"    Evidence: {i['line']}")
            lines.append(f"    Fix: {i['fix']}")
        lines.append("")
    lines.append(extra)
    (REPORTS/"SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nCombined summary: {REPORTS/'SUMMARY.md'}")

def scan(target: Path):
    bundles=find_bundles(target)
    if not bundles:
        print(f"No .tar/.tgz/.tar.gz/.zip found in {target}")
        print("Put AO bundles there, e.g. input/worker1_AOlogs.tar, then re-run ./scan.sh")
        return []
    results=[]
    for b in bundles:
        try: results.append(process_one(b, ANALYSIS))
        except Exception as e: print(f"FAILED {b}: {e}")
    write_summary(results)
    return results

def main():
    args=sys.argv[1:]
    watch="--watch" in args
    names=[a for a in args if not a.startswith("--")]
    target = INPUT / names[0] if names else INPUT
    if not target.exists():
        print(f"Folder not found: {target}")
        print("Create it and drop AO tars in, e.g. mkdir -p input/my-incident && cp *.tar input/my-incident/")
        return
    if watch:
        seen=set()
        print(f"Watching {target} every 30s - drop .tar files in, Ctrl+C to stop. No browser needed.")
        while True:
            bundles=find_bundles(target)
            new=[b for b in bundles if str(b) not in seen]
            if new:
                for b in new: seen.add(str(b))
                scan(target)
            time.sleep(30)
    else:
        scan(target)

if __name__=="__main__": main()
